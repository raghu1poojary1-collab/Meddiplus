/**
 * i18n manager with localStorage persistence, font class management,
 * and text crossfade animation support.
 */
class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("medipulse_lang") || "en";
    if (!translations[this.currentLang]) {
      this.currentLang = "en";
    }
    this.listeners = [];
  }

  init() {
    this.updateDomAttributes();
    this.applyTranslations();
  }

  getLang() {
    return this.currentLang;
  }

  get(key) {
    const dict = translations[this.currentLang] || translations.en;
    return dict[key] || translations.en[key] || key;
  }

  isRTL() {
    return translations[this.currentLang]?.dir === "rtl";
  }

  getSpeechLang() {
    return translations[this.currentLang]?.speechLang || "en-IN";
  }

  subscribe(listener) {
    this.listeners.push(listener);
  }

  updateDomAttributes() {
    const isRtl = this.isRTL();
    document.documentElement.setAttribute("dir", isRtl ? "rtl" : "ltr");
    document.documentElement.setAttribute("lang", this.currentLang);
    if (document.body) {
      document.body.classList.toggle("lang-rtl", isRtl);
      const scriptClasses = ["lang-kn", "lang-te", "lang-ta", "lang-ml", "lang-mr", "lang-hi", "lang-bn", "lang-ur", "lang-tcy"];
      scriptClasses.forEach(cls => document.body.classList.remove(cls));
      document.body.classList.add(`lang-${this.currentLang}`);
    }
    const select = document.getElementById("global-lang-select");
    if (select && select.value !== this.currentLang) {
      select.value = this.currentLang;
    }
  }

  setLang(lang) {
    if (!translations[lang] || lang === this.currentLang) return;
    
    this.currentLang = lang;
    localStorage.setItem("medipulse_lang", lang);

    // Update document direction and lang attribute
    this.updateDomAttributes();

    // Trigger crossfade transition on all translatable elements
    const translatableElements = document.querySelectorAll("[data-i18n], [data-i18n-placeholder], [data-i18n-title]");
    
    translatableElements.forEach(el => {
      el.classList.add("i18n-fade-out");
    });

    setTimeout(() => {
      this.applyTranslations();
      translatableElements.forEach(el => {
        el.classList.remove("i18n-fade-out");
        el.classList.add("i18n-fade-in");
        setTimeout(() => el.classList.remove("i18n-fade-in"), 250);
      });

      this.listeners.forEach(fn => fn(lang));
    }, 200);
  }

  applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const text = this.get(key);
      if (text) {
        el.textContent = text;
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      const text = this.get(key);
      if (text) {
        el.setAttribute("placeholder", text);
      }
    });

    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      const key = el.getAttribute("data-i18n-title");
      const text = this.get(key);
      if (text) {
        el.setAttribute("title", text);
      }
    });
  }
}

window.i18n = new I18nManager();
document.addEventListener("DOMContentLoaded", () => {
  window.i18n.init();
});

